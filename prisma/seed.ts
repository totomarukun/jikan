async function main() {
  const rows = [
    ...INVERTED.map((r) => toRubber(r, "RUBBER_INVERTED")),
    ...INVERTED_EXT.map((r) => toRubber(r, "RUBBER_INVERTED")),
    ...PIMPLE_OUT.map((r) => toRubber(r, "RUBBER_PIMPLE_OUT")),
    ...PIMPLE_OUT_EXT.map((r) => toRubber(r, "RUBBER_PIMPLE_OUT")),
    ...PIMPLE_LONG.map((r) => toRubber(r, "RUBBER_PIMPLE_LONG")),
    ...PIMPLE_LONG_EXT.map((r) => toRubber(r, "RUBBER_PIMPLE_LONG")),
    ...STICKY.map((r) => toRubber(r, "RUBBER_STICKY")),
    ...STICKY_EXT.map((r) => toRubber(r, "RUBBER_STICKY")),
    ...ANTI.map((r) => toRubber(r, "RUBBER_ANTI")),
    ...BLADES.map(toBlade),
    ...BLADES_EXT.map(toBlade),
  ];

  for (const row of rows) {
    await prisma.equipment.upsert({
      where: {
        manufacturer_name: {
          manufacturer: row.manufacturer,
          name: row.name,
        },
      },
      create: row,
      update: row,
    });
  }
  console.log(`Seeded ${rows.length} equipment items.`);
}

function toRubber(r: RubberRow, category: string) {
  const [manufacturer, name, officialSpeed, officialSpin, officialArc, hardness, price] = r;
  return {
    category,
    manufacturer,
    name,
    officialSpeed,
    officialSpin,
    officialArc,
    hardness,
    price,
    isActive: true,
  };
}

function toBlade(r: BladeRow) {
  const [manufacturer, name, officialSpeed, officialArc, bladeSubcategory, price] = r;
  return {
    category: "BLADE",
    manufacturer,
    name,
    officialSpeed,
    officialSpin: null,
    officialArc,
    hardness: null,
    bladeSubcategory,
    price,
    isActive: true,
  };
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
